"""No issue, phase or plan numbers in the code or the files beside it.

A comment that says only "see ISS-221" or "added in 148-02" points at a
planning record that is not in the repository, so a reader cannot follow it.
The reason belongs in the comment itself, and the history belongs in git.

This test scans the product code (Python, templates, CSS, JavaScript, shell
scripts, the Makefile, Dockerfile, Caddyfile, crontab.txt, docker-compose.yml,
entrypoint.sh) and the programmer
documents beside it (DESIGN.md, CLAUDE.md, ARCHITECTURE.md, scripts/README.md
and the README files under data/) for five shapes:

- an issue number: ``ISS-`` followed by digits;
- a phase number of two or more digits: ``Phase 62``, ``Phase 150.1``;
- a plan number: two or three digits, an optional ``.N``, a hyphen and two
  digits from ``00`` to ``19`` (``148-02``, ``143-13``, ``52.6-02``), not preceded by a digit, dot, hyphen or slash and
  not followed by a digit or hyphen, so dates (``2026-10-24``) and version
  ranges do not match.
- the name of a planning file: ``ISSUES.md``, ``STATE.md``, ``RESUME.md``, or
  a name with ``-PLAN``, ``-SUMMARY``, ``-DISCOVERY``, ``-RESEARCH`` or
  ``-EVIDENCE`` in it. These files are the maintainer's private record, not
  part of the repository;
- a review row: ``R-`` and three digits, or ``F-<word>-<digits>``, the row
  numbers of review registers that are not in the repository.

``Phase 2`` and other single-digit phases are the AI operator guide's own
steps (docs/AI-OPERATOR-GUIDE.md) and do not match. ``tests/`` and the
migrations are not scanned: a migration is a record of what was, and the tests
carry their own references.

A hit that is not a planning reference is fixed in the patterns above, never
added to ALLOWED.
"""

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

PATTERNS = {
    "issue number": re.compile(r"ISS-\d+"),
    "phase number": re.compile(r"Phase \d{2,}(\.\d+)?"),
    "plan number": re.compile(r"(?<![\d.\-/])[1-9]\d{1,2}(\.\d)?-[01]\d(?![\d\-])"),
    "planning file": re.compile(
        r"\bISSUES\.md\b|\bSTATE\.md\b|\bRESUME\.md\b|-(PLAN|SUMMARY|DISCOVERY|RESEARCH|EVIDENCE)\b"
    ),
    "review row": re.compile(r"\bR-\d{3}\b|\bF-[a-z]+-\d+\b"),
}

SUFFIXES = {".py", ".html", ".js", ".css", ".sh"}
NAMED_FILES = {"Makefile", "docker-compose.yml", "entrypoint.sh", "Dockerfile", "Caddyfile", "crontab.txt"}
DOCUMENTS = {"DESIGN.md", "CLAUDE.md", "ARCHITECTURE.md", "scripts/README.md"}

# Folders that hold no hand-written source: generated output, local data, caches.
SKIP_DIRS = {
    ".git", ".planning", "tests", "migrations", "__pycache__", "node_modules",
    "staticfiles", "media", "backups", "logs", "secrets", ".venv", "venv",
}
# Generated by the Tailwind binary at image build; not hand-written.
SKIP_FILES = {"static/css/output.css"}

#: (path, text on the line, reason). Each entry is a line that must keep its
#: reference for now; the reason says why.
ALLOWED = (
    (
        "core/management/commands/seed_merced_basins_from_selection.py",
        "Hand-selected in QGIS (Phase 62)",
        "stored demonstration text that the demo seeds into the database and "
        "a page shows; its wording is held for the maintainer's review",
    ),
)


def _scanned_files():
    for path in sorted(REPO_ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(REPO_ROOT)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]):
            continue
        name = rel.as_posix()
        if name in SKIP_FILES:
            continue
        if (
            path.suffix in SUFFIXES
            or (rel.name in NAMED_FILES and len(rel.parts) == 1)
            or name in DOCUMENTS
            or (rel.parts[0] == "data" and rel.name == "README.md")
        ):
            yield rel


def _allowed(name, line):
    return any(name == path and text in line for path, text, _ in ALLOWED)


def planning_references():
    """Every scanned line holding a planning reference, as ``path:line: text``."""
    hits = []
    for rel in _scanned_files():
        name = rel.as_posix()
        try:
            text = (REPO_ROOT / rel).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            if any(p.search(line) for p in PATTERNS.values()) and not _allowed(name, line):
                hits.append(f"{name}:{number}: {line.strip()}")
    return hits


def test_no_planning_references_in_code():
    hits = planning_references()
    assert hits == [], (
        f"{len(hits)} lines point at the planning record instead of giving "
        "their reason. Write the reason in place, or delete a note that only "
        "says something changed (git log holds the history):\n" + "\n".join(hits)
    )


def test_every_allowed_line_still_exists():
    """An ALLOWED entry whose line is gone is removed, so the list cannot grow stale."""
    missing = []
    for path, text, _ in ALLOWED:
        file = REPO_ROOT / path
        if not file.exists() or text not in file.read_text(encoding="utf-8"):
            missing.append(f"{path}: {text}")
    assert missing == [], "ALLOWED entries with no matching line: " + "; ".join(missing)
